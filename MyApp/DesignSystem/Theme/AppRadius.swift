import CoreGraphics

/// Corner radius scale.
enum AppRadius {
    /// Chips, small thumbnails.
    static let small: CGFloat = 8
    /// Buttons, text fields, tiles.
    static let medium: CGFloat = 12
    /// Cards.
    static let large: CGFloat = 16
    /// Banners and hero cards.
    static let xLarge: CGFloat = 20
}
